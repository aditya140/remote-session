        stack.wait(lambda: replay(b"PAUSED_OWNER_ALIVE", local=True), "owner survives connector pause")
        command(host + ["up", "--no-service"])
        stack.wait(lambda: remote("reconcile", machine, launch["key"])["session"] == session, "same start after reconnect", seconds=40)
        stack.wait(lambda: replay(b"PAUSED_OWNER_ALIVE"), "reconnected output")
        passed("connector pause preserves the same running session and original start identity")
        remote("revoke", machine, "--yes")
        revoked = True
        remote("send", machine, session, "MUST_NOT_BE_SENT", "--enter", success=False)
