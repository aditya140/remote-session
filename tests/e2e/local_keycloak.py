def identity_failures(stack, credentials, tokens, passed):
    def enabled(value):
        token = stack.http("/realms/master/protocol/openid-connect/token", identity=True, form={
            "grant_type": "password", "client_id": "admin-cli", "username": "admin", "password": credentials["admin"]})["access_token"]
        opener = urllib.request.build_opener(urllib.request.ProxyHandler({}), urllib.request.HTTPSHandler(
            context=ssl.create_default_context(cafile=str(stack.args.state / "certificates/ca.pem"))))
        request = urllib.request.Request("https://localhost:9443/admin/realms/qgr-local/users/" + USERS["bob"],
            method="PUT", data=json.dumps({"enabled": value}).encode(),
            headers={"Authorization": "Bearer " + token, "Content-Type": "application/json"})
        with opener.open(request, timeout=5) as response:
            assert response.status == 204
    def denied(token, expected):
        try:
            stack.http("/v1/machines", token=token)
        except urllib.error.HTTPError as error:
            return error.code in expected
        return False
    nodes = [f"gateway-{node}" for node in range(1, 5)]
    try:
        enabled(False)
        stack.call("restart", *nodes)
        stack.wait(lambda: denied(tokens["bob"]["access_token"], (403,)), "disabled real account denied", seconds=45)
        passed("Keycloak account disablement is enforced on fresh gateway directory verification")
    finally:
        enabled(True)
    def keys():
        return sorted(stack.http(REALM + "/protocol/openid-connect/certs", identity=True)["keys"], key=lambda key: key["kid"])
    original_keys = keys()
    try:
        stack.call("stop", "--timeout", "10", "directory", "keycloak")
        stack.call("restart", *nodes)
        stack.wait(lambda: denied(tokens["bob"]["access_token"], (503,)), "provider outage fails closed", seconds=45)
    finally:
        stack.call("start", "keycloak", "directory")
        stack.wait(lambda: ready(stack), "identity provider recovery", seconds=90)
    stack.wait(lambda: stack.http("/v1/machines", token=tokens["bob"]["access_token"]) == [], "real account recovery", seconds=60)
    assert keys() == original_keys
    passed("provider outage denies fresh authorization; recovery preserves realm signing keys and user identity")


